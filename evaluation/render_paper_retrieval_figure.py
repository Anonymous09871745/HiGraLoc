"""Paper-style retrieval visualization for KITTI360Pose.

This module renders a single query in a publication-friendly layout:
- left: query text
- middle: query-centered BEV (50x50m by default)
- right: top-5 coarse retrieval submaps, each centered on the retrieved cell
  with the fine-predicted coordinate marked

The script expects a saved retrieval JSON generated by
`evaluation.pipeline_three_branch_with_fine`.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Optional, Sequence

import cv2
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from dataloading.kitti360pose.cells import Kitti360CoarseDatasetMulti
from evaluation.visualize_three_branch_retrieval import load_records
from evaluation.render_query_bev import render_bev_from_points
from datapreparation.kitti360pose.utils import CLASS_TO_COLOR, SCENE_NAMES, SCENE_NAMES_TEST, SCENE_NAMES_VAL


def _dataset_object_points(cell) -> tuple[np.ndarray, np.ndarray]:
    points = []
    colors = []
    for obj in getattr(cell, "objects", []):
        if getattr(obj, "label", "") == "pad":
            continue
        xyz = np.asarray(obj.xyz, dtype=np.float32)
        rgb = getattr(obj, "rgb", None)
        if rgb is None:
            c = np.array(CLASS_TO_COLOR.get(obj.label, (128, 128, 128)), dtype=np.uint8)
            rgb = np.tile(c[None, :], (len(xyz), 1))
        else:
            rgb = np.asarray(rgb)
            if rgb.max() <= 1.0:
                rgb = (rgb * 255).astype(np.uint8)
            else:
                rgb = rgb.astype(np.uint8)
        # map normalized cell coords to world bbox for a more paper-like BEV
        x0, y0, z0, x1, y1, z1 = cell.bbox_w
        sx = max(x1 - x0, 1e-6)
        sy = max(y1 - y0, 1e-6)
        sz = max(z1 - z0, 1e-6)
        world = xyz.copy()
        world[:, 0] = x0 + xyz[:, 0] * sx
        world[:, 1] = y0 + xyz[:, 1] * sy
        if world.shape[1] > 2:
            world[:, 2] = z0 + xyz[:, 2] * sz
        points.append(world)
        colors.append(rgb)
    if points:
        return np.concatenate(points, axis=0), np.concatenate(colors, axis=0)
    return np.zeros((0, 3), dtype=np.float32), np.zeros((0, 3), dtype=np.uint8)


def _load_multiscene_dataset(base_path: str, scene: str):
    scene_lower = scene.lower()
    if scene_lower in {"test", "testset"}:
        scenes = SCENE_NAMES_TEST
    elif scene_lower in {"val", "valid", "validation"}:
        scenes = SCENE_NAMES_VAL
    elif scene in SCENE_NAMES:
        scenes = [scene]
    else:
        scenes = [scene]
    return Kitti360CoarseDatasetMulti(base_path, scenes, transform=None, shuffle_hints=False, flip_poses=False)


def _add_distance_box(img: np.ndarray, distance_m: float, is_correct: bool, label: str = "d") -> None:
    """Draw a fixed-size distance annotation in the top-right corner.

    Important implementation detail:
    The old version sized the box from the text width. A short value such as
    "D: 2.85m" and a long value such as "D: 5636.38m" therefore produced
    visibly different boxes. For paper figures we want every panel to have the
    same annotation geometry, so this function uses fixed pixel dimensions and
    right-aligns the text inside that fixed box.

    This function must be called *after* a panel has been cropped and resized.
    If the annotation is drawn before crop/resize, the crop operation may cut a
    different amount from each panel, and interpolation will again make the
    final boxes look inconsistent.
    """

    text = f"{label}: {distance_m:.2f}m"
    color = (0, 255, 0) if is_correct else (0, 0, 255)
    font = cv2.FONT_HERSHEY_SIMPLEX
    scale = 1.55
    thickness = 3

    # Fixed annotation geometry for the final 1400x1400 panels.
    # Keeping these values independent of text length guarantees that green and
    # red boxes have the same visible size.
    margin = 26
    box_w = 390
    box_h = 94
    text_pad_x = 24
    text_baseline_pad = 28

    x2 = img.shape[1] - margin
    y1 = margin
    x1 = x2 - box_w
    y2 = y1 + box_h

    # White fill improves text readability on dark point-cloud regions, while
    # the colored border still encodes correct/incorrect status.
    cv2.rectangle(img, (x1, y1), (x2, y2), (255, 255, 255), thickness=-1)
    cv2.rectangle(img, (x1, y1), (x2, y2), color, thickness=8)

    (tw, _), baseline = cv2.getTextSize(text, font, scale, thickness)
    text_x = x2 - text_pad_x - tw
    text_y = y2 - text_baseline_pad - baseline
    cv2.putText(img, text, (text_x, text_y), font, scale, color, thickness, cv2.LINE_AA)


def _crop_and_resize_panel(panel: np.ndarray, final_size: int = 1400, padding: int = 120) -> np.ndarray:
    """Crop visible point-cloud content and resize to the paper panel size.

    The crop mask intentionally ignores the top-right annotation because the
    annotation is drawn later. This prevents the distance box from influencing
    the crop region. If the annotation participates in the crop mask, panels
    with different text widths can be cropped differently, which is one of the
    reasons the previous distance boxes looked unequal after resizing.
    """

    gray = cv2.cvtColor(panel, cv2.COLOR_BGR2GRAY)
    ys, xs = np.where(gray < 250)
    if len(xs) > 0 and len(ys) > 0:
        x0 = max(xs.min() - padding, 0)
        x1 = min(xs.max() + padding, panel.shape[1])
        y0 = max(ys.min() - padding, 0)
        y1 = min(ys.max() + padding, panel.shape[0])
        panel = panel[y0:y1, x0:x1]
    return cv2.resize(panel, (final_size, final_size), interpolation=cv2.INTER_CUBIC)


def _find_query_cell(record, all_cells: dict[str, object]):
    """Find the dataset cell corresponding to the query.

    Retrieval JSONs can contain an empty `query_points_xy` field, so the GT
    panel must be rebuilt from the original dataset. In this dataset the query
    id normally has the same format as the cell id, for example `0003_0634`.
    Older code truncated the id to the first 10 characters, which is fragile and
    can silently fail for ids with a different length. This helper tries exact
    matching first, then falls back to prefix/substring matching only as a last
    resort.
    """

    query_id = str(record.query_id)
    if query_id in all_cells:
        return all_cells[query_id]

    # Some records may append extra suffixes to the query id. In that case the
    # real cell id is still usually a prefix of `query_id`.
    for cell_id, cell in all_cells.items():
        cell_id = str(cell_id)
        if query_id.startswith(cell_id) or cell_id.startswith(query_id):
            return cell

    # Last-resort fallback for non-standard serialized ids.
    for cell_id, cell in all_cells.items():
        cell_id = str(cell_id)
        if query_id in cell_id or cell_id in query_id:
            return cell

    return None


def _render_dataset_cell_panel(cell, center_xy: tuple[float, float], bev_size: float) -> np.ndarray:
    """Render one cell from dataset object points around a world-coordinate center.

    Object coordinates in KITTI360Pose cells are normalized to the cell bounding
    box. `_dataset_object_points` converts them back to world coordinates before
    rendering. Centering the crop at `center_xy` makes the GT panel show the
    real query neighborhood rather than relying on `query_points_xy` in the JSON.
    """

    points, colors = _dataset_object_points(cell)
    return render_bev_from_points(
        points,
        colors,
        center_xy,
        size_m=bev_size,
        img_size=1024,
        point_radius=7,
        query_marker=False,
    )


def render_query_and_topk(base_path: str, scene: str, query_idx: int, retrieval_json: str, out_png: str, bev_size: float = 50.0) -> None:
    """Render a paper-style strip for one query.

    Main visual controls:
    - `bev_size`: physical crop size in meters around the center of each panel.
      Smaller values zoom in more strongly, making the point cloud appear larger.
    - `point_radius` in `render_bev_from_points(...)`: makes each point thicker.
    - crop padding (`xs.min() - 120`, `ys.min() - 120`): tighter crop => bigger cloud.
    - `gap`: controls spacing between panels.
    - `thickness` of the outer box: controls how bold the green/red frame looks.

    Layout:
    - Leftmost panel: ground-truth query point cloud rendered as a BEV.
    - Right 5 panels: coarse retrieval candidates with GT and predicted positions.
    """
    ds = _load_multiscene_dataset(base_path, scene)
    records = load_records(retrieval_json)
    record = records[query_idx]
    all_cells = {str(c.id): c for c in ds.all_cells}

    # -------------------------
    # 1) Build the GT panel
    # -------------------------
    # Left panel: render the GT BEV directly from the original dataset cell.
    # Do NOT use `record.query_points_xy` here. In your `final_retrieval_100.json`
    # this field is empty, so drawing from it inevitably produces a blank panel
    # with only the manually drawn red GT dot. Reading the cell from `ds.all_cells`
    # guarantees that the original point cloud/object points are available.
    gt_cell = _find_query_cell(record, all_cells)

    if gt_cell is not None:
        gt_panel = _render_dataset_cell_panel(gt_cell, record.gt_xy, bev_size)
    else:
        # Fallback if the query cell cannot be found. This should be rare; when
        # it happens we keep a visible warning-like panel rather than silently
        # drawing an apparently valid but empty point cloud.
        gt_panel = np.ones((1024, 1024, 3), dtype=np.uint8) * 255

    # Draw the GT marker after the dataset point cloud has been rendered. The
    # marker is red and centered at the true query pose, so the left panel shows
    # both the local scene geometry and the exact query location.
    cv2.circle(gt_panel, (512, 512), 18, (0, 0, 255), thickness=-1)

    # Crop/resize before adding the distance box. This keeps the distance box
    # independent of crop geometry and makes its final size consistent.
    gt_panel = _crop_and_resize_panel(gt_panel)

    # -------------------------
    # 2) Build Top-5 candidate panels
    # -------------------------
    panels = [gt_panel]
    gt_distance = float(np.linalg.norm(np.asarray(record.gt_xy) - np.asarray(record.gt_xy)))
    _add_distance_box(panels[0], gt_distance, True, label="GT")

    for idx, cand in enumerate(record.candidates[:5]):
        cand_cell = all_cells[cand.cell_id]
        cpts, ccols = _dataset_object_points(cand_cell)
        center = cand.center_xy
        bev_c = render_bev_from_points(cpts, ccols, center, size_m=bev_size, img_size=1024, point_radius=7, query_marker=False)

        cx, cy = center
        half = bev_size / 2.0
        scale = 1024 / bev_size

        # GT position in each candidate panel: single solid red circle.
        gx = (record.gt_xy[0] - (cx - half)) * scale
        gy = 1024 - (record.gt_xy[1] - (cy - half)) * scale
        gt_px = (int(round(gx)), int(round(gy)))
        cv2.circle(bev_c, gt_px, 18, (0, 0, 255), thickness=-1)

        # Prediction position in each candidate panel: single solid blue circle.
        pred_xy = cand.fine_xy if cand.fine_xy is not None else cand.center_xy
        fx = (pred_xy[0] - (cx - half)) * scale
        fy = 1024 - (pred_xy[1] - (cy - half)) * scale
        pred_px = (int(round(fx)), int(round(fy)))
        cv2.circle(bev_c, pred_px, 18, (255, 0, 0), thickness=-1)

        pred_distance = float(np.linalg.norm(np.asarray(pred_xy) - np.asarray(record.gt_xy)))

        # Strong crop: make the occupied region larger in the final panel.
        # The distance box is intentionally NOT drawn yet; otherwise the box
        # itself participates in the crop mask and can be scaled differently per
        # panel. We draw it only after `_crop_and_resize_panel` returns the final
        # 1400x1400 image.
        bev_c = _crop_and_resize_panel(bev_c)
        _add_distance_box(bev_c, pred_distance, pred_distance <= 10.0, label="D")

        panels.append(bev_c)

    # -------------------------
    # 3) Stitch into a horizontal strip
    # -------------------------
    gap = 70  # increase spacing between panels
    height = panels[0].shape[0]
    width = sum(im.shape[1] for im in panels) + gap * (len(panels) - 1)
    strip = np.ones((height, width, 3), dtype=np.uint8) * 255
    x = 0
    for im, panel_idx in zip(panels, range(len(panels))):
        h, w = im.shape[:2]
        strip[0:h, x:x + w] = im
        dist_gt_to_center = 0.0 if panel_idx == 0 else float(np.linalg.norm(np.asarray(record.gt_xy) - np.asarray(record.candidates[panel_idx - 1].center_xy)))
        box_color = (0, 255, 0) if dist_gt_to_center <= 10.0 else (0, 0, 255)
        cv2.rectangle(strip, (x, 0), (x + w - 1, h - 1), box_color, thickness=30)
        x += w + gap

    Path(out_png).parent.mkdir(parents=True, exist_ok=True)
    cv2.imwrite(str(out_png), strip)


def parse_args(argv: Optional[Sequence[str]] = None) -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Render paper-style retrieval figure for one query.")
    p.add_argument("--base_path", required=True)
    p.add_argument("--scene", required=True)
    p.add_argument("--query_idx", type=int, default=0)
    p.add_argument("--retrieval_json", required=True)
    p.add_argument("--output", required=True)
    p.add_argument("--bev_size", type=float, default=50.0)
    return p.parse_args(argv)


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = parse_args(argv)
    render_query_and_topk(args.base_path, args.scene, args.query_idx, args.retrieval_json, args.output, bev_size=args.bev_size)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
